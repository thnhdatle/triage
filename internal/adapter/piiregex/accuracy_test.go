var update = flag.Bool("update", false, "rewrite testdata/pii/REPORT.md")

const (
	dataDir          = "../../../testdata/pii"
	recallStrong     = 0.99
	recallWeak       = 0.95
	maxNegativeFPAvg = 0.02
)

func loadSamples(t *testing.T, name string) []gen.Sample {
	t.Helper()
	f, err := os.Open(filepath.Join(dataDir, name))
	require.NoError(t, err)
	defer f.Close()
	var out []gen.Sample
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		var s gen.Sample
		require.NoError(t, json.Unmarshal(sc.Bytes(), &s))
		out = append(out, s)
	}
	require.NoError(t, sc.Err())
	return out
}

type tally struct{ tp, fp, fn, negHits int }

func (c tally) precision() float64 {
	if c.tp+c.fp == 0 {
		return 1
	}
	return float64(c.tp) / float64(c.tp+c.fp)
}

func (c tally) recall() float64 {
	if c.tp+c.fn == 0 {
		return 1
	}
	return float64(c.tp) / float64(c.tp+c.fn)
}

func minRecall(typ string) float64 {
	switch typ {
	case TypePhone, TypeVNCCCD, TypeStreetAddress:
		return recallWeak
	}
	return recallStrong
}

func evaluate(t *testing.T, d *Detector, positives, negatives []gen.Sample) (map[string]*tally, int) {
	t.Helper()
	res := map[string]*tally{}
	get := func(typ string) *tally {
		if res[typ] == nil {
			res[typ] = &tally{}
		}
		return res[typ]
	}
	for _, s := range positives {
		fs, err := d.Detect(context.Background(), s.Text)
		require.NoError(t, err)
		want := map[gen.Span]bool{}
		for _, sp := range s.Spans {
			want[sp] = true
		}
		for _, f := range fs {
			sp := gen.Span{Start: f.Start, End: f.End, Type: f.Type}
			if want[sp] {
				get(f.Type).tp++
				delete(want, sp)
			} else {
				get(f.Type).fp++
			}
		}
		for sp := range want {
			get(sp.Type).fn++
		}
	}
	hits := 0
	for _, s := range negatives {
		fs, err := d.Detect(context.Background(), s.Text)
		require.NoError(t, err)
		if len(fs) > 0 {
			hits++
		}
		for _, f := range fs {
			get(f.Type).negHits++
		}
	}
	return res, hits
}

func TestDetector_Detect_PrecisionRecallOnLabelledData(t *testing.T) {
	t.Parallel()
	positives := loadSamples(t, gen.LabelledFile)
	negatives := loadSamples(t, gen.NegativesFile)
	require.GreaterOrEqual(t, len(positives), 1000)
	require.Len(t, negatives, 1000)

	on, err := New(WithStreetAddress(true))
	require.NoError(t, err)
	off, err := New()
	require.NoError(t, err)

	res, hitsOn := evaluate(t, on, positives, negatives)
	_, hitsOff := evaluate(t, off, positives, negatives)

	for typ, c := range res {
		assert.GreaterOrEqualf(t, c.recall(), minRecall(typ), "recall of %s (tp=%d fn=%d)", typ, c.tp, c.fn)
	}
	assert.LessOrEqual(t, float64(hitsOn)/float64(len(negatives)), maxNegativeFPAvg, "FP rate, street enabled")
	assert.LessOrEqual(t, float64(hitsOff)/float64(len(negatives)), maxNegativeFPAvg, "FP rate, default")

	if *update {
		writeReport(t, res, len(positives), len(negatives), hitsOff, hitsOn)
	}
}

func writeReport(t *testing.T, res map[string]*tally, nPos, nNeg, hitsOff, hitsOn int) {
	t.Helper()
	var b bytes.Buffer
	b.WriteString("# PII detector report\n\n")
	b.WriteString("Generated by `go test ./internal/adapter/piiregex -run PrecisionRecall -update`; do not edit.\n")
	b.WriteString("Spans match on exact byte range and type.\n\n")
	fmt.Fprintf(&b, "- labelled strings: %d, PII-free prompts: %d\n", nPos, nNeg)
	fmt.Fprintf(&b, "- false-positive rate on PII-free prompts: %.2f%% (%d/%d) default, "+
		"%.2f%% (%d/%d) with street_address\n\n",
		100*float64(hitsOff)/float64(nNeg), hitsOff, nNeg, 100*float64(hitsOn)/float64(nNeg), hitsOn, nNeg)
	b.WriteString("| detector | class | TP | FP | FN | precision | recall | min recall | FP on negatives |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|\n")
	for _, typ := range strings.Split(gen.AllTypes, "|") {
		c := res[typ]
		if c == nil {
			c = &tally{}
		}
		class := "structural"
		switch typ {
		case TypeCreditCard, TypeIBAN:
			class = "checksum"
		case TypePhone, TypeVNCCCD:
			class = "context"
		case TypeStreetAddress:
			class = "heuristic"
		}
		fmt.Fprintf(&b, "| %s | %s | %d | %d | %d | %.4f | %.4f | %.2f | %d |\n",
			typ, class, c.tp, c.fp, c.fn, c.precision(), c.recall(), minRecall(typ), c.negHits)
	}
	require.NoError(t, os.WriteFile(filepath.Join(dataDir, "REPORT.md"), b.Bytes(), 0o600))
}
